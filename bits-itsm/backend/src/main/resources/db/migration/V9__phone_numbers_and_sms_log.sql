-- Real (optional) mobile numbers instead of generated ones, and a persistent SMS log.
-- SMS is only attempted for users who have a number; everyone else is logged as NO_NUMBER.
alter table app_users add column if not exists phone varchar(20);

create table if not exists sms_messages (
    id bigint generated by default as identity primary key,
    sent_at timestamp with time zone not null,
    recipient_id bigint,              -- no foreign key: logging must never block or fail a business transaction
    phone varchar(20),
    body varchar(1000) not null,
    receipt varchar(40),
    status varchar(16) not null check (status in ('SENT', 'FAILED', 'NO_NUMBER'))
);
create index if not exists sms_messages_sent_at on sms_messages (sent_at desc);
